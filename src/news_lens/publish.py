_INDEX_FILTER_JS = """\
<script>
(function() {
  var input = document.getElementById('q');
  var cards = Array.prototype.slice.call(document.querySelectorAll('.report-card'));
  var count = document.getElementById('count');
  function refresh() {
    var q = (input.value || '').toLowerCase().trim();
    var shown = 0;
    cards.forEach(function(c) {
      var hay = (c.getAttribute('data-search') || '').toLowerCase();
      var match = !q || hay.indexOf(q) !== -1;
      c.hidden = !match;
      if (match) shown += 1;
    });
    count.textContent = shown + ' of ' + cards.length + ' reports';
  }
  if (input) input.addEventListener('input', refresh);
  refresh();
})();
</script>
"""


def _render_card(meta: ReportMetadata) -> str:
    date_label = meta.generated.strftime("%Y-%m-%d") if meta.generated else ""
    stats = [
        f"{meta.n_articles} article{'' if meta.n_articles == 1 else 's'}",
        f"{meta.n_outlets} outlet{'' if meta.n_outlets == 1 else 's'}",
        f"{meta.n_claims} claim{'' if meta.n_claims == 1 else 's'}",
    ]
    if meta.has_omissions:
        stats.append("omissions flagged")
    stats_html = "".join(f'<span class="stat">{_esc(s)}</span>' for s in stats)
    haystack = " ".join([
        meta.title, meta.description, meta.filename, date_label,
    ])
    return (
        f'<article class="report-card" data-search="{_esc(haystack)}">'
        f'<a href="reports/{_esc(meta.filename)}">'
        f'<h2>{_esc(meta.title)}</h2>'
        f'<p class="desc">{_esc(meta.description)}</p>'
        f'<div class="stats">{stats_html}</div>'
        f'<div class="date">{_esc(date_label)}</div>'
        "</a></article>"
    )


def build_index(docs_dir: Path) -> Path:
    """Walk docs_dir/reports/*.html and write docs_dir/index.html."""
    reports_dir = docs_dir / "reports"
    if not reports_dir.is_dir():
        raise SystemExit(
            f"error: {reports_dir} not found. Create it and drop your "
            "report HTML files there."
        )

    metas: list[ReportMetadata] = []
    for path in sorted(reports_dir.glob("*.html")):
        meta = extract_metadata(path)
        if meta is None:
            print(
                f"WARN: {path.name} does not look like a News Lens report; "
                "skipping.",
                file=sys.stderr,
            )
            continue
        metas.append(meta)

    metas.sort(
        key=lambda m: m.generated or datetime.min,
        reverse=True,
    )

    cards_html = "".join(_render_card(m) for m in metas)
    body = (
        _INDEX_HERO
        + '<div class="filter-bar">'
        + '<input type="search" id="q" placeholder="Filter by story, outlet, or date" '
        'aria-label="Filter reports">'
        + f'<span class="count" id="count">{len(metas)} report{"" if len(metas) == 1 else "s"}</span>'
        + "</div>"
        + f'<div class="reports">{cards_html}</div>'
        + _INDEX_FOOTER
    )

    page = (
        "<!DOCTYPE html>"
        '<html lang="en">'
        "<head>"
        '<meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width, initial-scale=1">'
        "<title>News Lens — published reports</title>"
        '<meta property="og:title" content="News Lens — published reports">'
        '<meta property="og:description" content="Cross-outlet coverage matrices for individual news stories.">'
        '<meta property="og:type" content="website">'
        f"<style>{_INDEX_CSS}</style>"
        "</head>"
        '<body><div class="page">'
        f"{body}"
        "</div>"
        f"{_INDEX_FILTER_JS}"
        "</body></html>"
    )

    out = docs_dir / "index.html"
    out.write_text(page, encoding="utf-8")
    return out


def main(argv: Optional[list[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m news_lens.publish",
        description=(
            "Build a landing page over a curated set of News Lens reports."
        ),
    )
    sub = parser.add_subparsers(dest="cmd", required=True)

    build = sub.add_parser(
        "build",
        help="Walk docs/reports/*.html and write docs/index.html.",
    )
    build.add_argument(
        "docs_dir",
        type=Path,
        help="Path to the docs/ folder containing a reports/ subfolder.",
    )

    args = parser.parse_args(argv)
    if args.cmd == "build":
        out = build_index(args.docs_dir)
        print(f"Wrote {out}", file=sys.stderr)
        return 0
    parser.error(f"unknown command: {args.cmd}")
    return 2


if __name__ == "__main__":
    sys.exit(main())
