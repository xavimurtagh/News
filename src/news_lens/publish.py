"""Build a static index page over a folder of curated reports.

The CLI emits one self-contained HTML report per run. To put a curated
set of those reports on the public internet, drop them in
`docs/reports/` and run `python -m news_lens.publish build docs/`. This
walks the reports, extracts each report's metadata (title, generated
date, article / outlet / claim counts, the first topline bullet as a
description) and writes `docs/index.html` — a landing page with one
card per report, sorted newest-first.

The intent is **editorial curation, not automation**: you decide which
reports go public, when, and how they're framed. The accompanying
`.github/workflows/publish.yml` deploys whatever is in `docs/` to
GitHub Pages.

Run `python -m news_lens.publish --help` for the CLI surface.
"""

from __future__ import annotations

import argparse
import html
import re
import sys
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
from typing import Optional


@dataclass
class ReportMetadata:
    """What the index page shows about one report."""

    filename: str
    title: str
    description: str
    generated: Optional[datetime]
    n_articles: int
    n_outlets: int
    n_claims: int
    has_omissions: bool


_META_LINE_RE = re.compile(
    r'<div class="meta">'
    r"(?P<n_articles>\d+)\s+articles?"
    r".*?(?P<n_outlets>\d+)\s+outlets?"
    r".*?(?P<n_claims>\d+)\s+canonical\s+claims?"
    r".*?generated\s+(?P<generated>[\d:\s\-UTC]+)"
    r"</div>",
    re.IGNORECASE | re.DOTALL,
)
_OG_TITLE_RE = re.compile(
    r'<meta\s+property="og:title"\s+content="([^"]+)"', re.IGNORECASE
)
_OG_DESC_RE = re.compile(
    r'<meta\s+property="og:description"\s+content="([^"]+)"', re.IGNORECASE
)
_OMISSIONS_RE = re.compile(r'id="omissions"', re.IGNORECASE)


def _esc(value: str) -> str:
    return html.escape(value or "", quote=True)


def _parse_generated(stamp: str) -> Optional[datetime]:
    stamp = stamp.strip().replace(" UTC", "").strip()
    for fmt in ("%Y-%m-%d %H:%M", "%Y-%m-%d"):
        try:
            return datetime.strptime(stamp, fmt)
        except ValueError:
            continue
    return None


def extract_metadata(html_path: Path) -> Optional[ReportMetadata]:
    """Read a rendered report and pull out the fields the index needs.

    Returns None if the file doesn't look like a News Lens report
    (no meta line found). Permissive on the title/description: a report
    rendered before OG tags were added still parses; it just gets a
    fallback label.
    """
    try:
        text = html_path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return None

    meta_match = _META_LINE_RE.search(text)
    if not meta_match:
        return None

    n_articles = int(meta_match["n_articles"])
    n_outlets = int(meta_match["n_outlets"])
    n_claims = int(meta_match["n_claims"])
    generated = _parse_generated(meta_match["generated"])

    og_title_match = _OG_TITLE_RE.search(text)
    title = (
        og_title_match.group(1)
        if og_title_match
        else html_path.stem.replace("_", " ").replace("-", " ").title()
    )

    og_desc_match = _OG_DESC_RE.search(text)
    description = og_desc_match.group(1) if og_desc_match else ""

    return ReportMetadata(
        filename=html_path.name,
        title=title,
        description=description,
        generated=generated,
        n_articles=n_articles,
        n_outlets=n_outlets,
        n_claims=n_claims,
        has_omissions=bool(_OMISSIONS_RE.search(text)),
    )


